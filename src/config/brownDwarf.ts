/**
 * Коричневый карлик: запекание облачного поля и переключение LOD.
 *
 * Яркость импостора ручки не имеет НАМЕРЕННО: билборд сэмплит ту же кубмапу
 * через тот же чанк brownDwarfSurface, что и диск, — любой множитель поверх
 * воссоздал бы шов на переключении (тот же контракт, что у config/star.ts).
 */
export interface BrownDwarfConfig {
  brownDwarf: {
    /**
     * Грань кубмапы облачного поля, тексели. 2048 — 22.8 текселя на градус:
     * тело диаметром 2600 px на экране ещё не мылится. Память: 6 граней ×
     * 2048² × 2 байта = 50 МБ, с мипами ≈ 67 МБ.
     */
    cubeSize: number
    /**
     * Итераций полулагранжевой адвекции при запекании. Складки накапливаются
     * с числом шагов: именно они дают филаменты и рваные пояса. Ниже ~12 поле
     * остаётся шумом с полосами.
     */
    advectionSteps: number
    /**
     * Доля свежего шума, подмешиваемая на каждом шаге. Компенсирует численную
     * диффузию билинейной выборки — без неё поле за 24 шага замыливается.
     */
    noiseInjection: number
    /** Гистерезис LOD — доля дистанции переключения (см. star.lodHysteresis) */
    lodHysteresis: number
  }
}

export const brownDwarf: BrownDwarfConfig = {
  brownDwarf: {
    cubeSize: 2048,
    advectionSteps: 24,
    noiseInjection: 0.05,
    lodHysteresis: 0.05
  }
}
