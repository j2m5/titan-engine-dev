/**
 * Конфиг качества рендеринга чёрных дыр (спецификация §4).
 * Свойства машины, а не объекта: пер-объектные параметры живут
 * в renderingObject.data (IBlackHoleRenderingObject)
 */
export interface BlackHoleQualityConfig {
  /**
   * Шаг интегрирования уравнения Бине по углу, рад.
   * 0.05 — качество (потолок ~188 шагов до 3π), 0.08 — экономия (~118 шагов)
   * Значение связано с MAX_STEPS в BlackHoleShaderTemplate — связку стережёт
   * tests/blackHole/IntegratorBudget.spec.ts
   */
  integrationDphi: number
  /**
   * Порог переключения L0 → L1 (импостор): экранный диаметр зоны
   * симуляции в пикселях, при котором лензирование уже неразличимо.
   * Считается честной формулой (distanceForApparentSize, BlackHoleLod) по
   * живым fov и высоте вьюпорта. 45 ≈ прежний фактический порог: старая
   * известно-неверная формула при номинальных 35 переключала на 44.7
   * фактических пикселях — точка переключения НЕ сместилась
   */
  lodPixels: number
  /**
   * Пол видимого размера импостора: экранный диаметр зоны симуляции в
   * пикселях, ниже которого дыра перестаёт сжиматься и рисуется этим
   * размером с полной яркостью — та же конвенция, что у звёздных
   * импосторов (STAR_IMPOSTOR_PIXELS). Без пола тонкое кольцо диска
   * усредняется растеризацией и дыра гаснет вместе с блумом и бликом.
   *
   * ОБЯЗАН быть не выше lodPixels: пол, сработавший до переключения, дал бы
   * скачок размера ровно на стыке LOD. Работает только у дыр с диском —
   * голой дыре нечего светить, а раздутая тень крупнее физической.
   */
  impostorPixels: number
  /**
   * Гистерезис LOD (доля дистанции переключения), защита от мигания
   * на границе: переключение вверх происходит на distance·(1−hysteresis)
   */
  lodHysteresis: number
}

export interface BlackHoleConfig {
  blackHole: BlackHoleQualityConfig
}

export const blackHole: BlackHoleConfig = {
  blackHole: {
    integrationDphi: 0.05,
    lodPixels: 45,
    impostorPixels: 24,
    lodHysteresis: 0.3
  }
}
