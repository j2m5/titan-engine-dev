/**
 * Конфиг фона сцены. Кубмапа восьмибитная, поэтому самая яркая звезда в ней
 * равна 1.0 и не может пробить порог блума (BLOOM_OPTIONS.luminanceThreshold).
 * Расширение хайлайтов подтягивает верх диапазона за 1.0, оставляя всё ниже
 * порога нетронутым.
 */
export interface BackgroundConfig {
  background: {
    /** Ниже этого значения фон не меняется вовсе */
    highlightThreshold: number
    /** Во сколько раз растягивается превышение порога; 1 — расширение выключено */
    highlightBoost: number
  }
}

/**
 * Значения подобраны на приёмке 02.08.2026 замером, а не на глаз.
 *
 * Порог 0.4, а не «почти единица», из-за минификации: расширение хайлайтов
 * идёт после выборки, грань кубмапы приходит на экран уменьшенной, ядро
 * звезды усредняется с соседями ещё в фильтре, и до расширения доживает уже
 * не 1.0. Исторический замер (грань `pz`, тогда ещё 6000², масштаб экрана
 * 2.7×): пикселей ярче 0.8 при 1:1 — 6473, после уменьшения — 55. Поэтому
 * порог 0.8 (первая проба) не менял картинку вовсе: сравнение кадров дало
 * средний модуль разности 0.09 из 255.
 *
 * Затронуто порогом 0.4 не больше ~0.04% пикселей неба — это ядра ярчайших
 * звёзд и самые светлые сгустки Млечного Пути. Замер именно на этой паре
 * значений на гранях 6000² (кадры «до/после» в одной позе камеры): средняя
 * яркость области полосы Млечного Пути 33.75 → 34.58, то есть +2.5%, а
 * пикселей ярче 200 в ней стало втрое больше (72 → 231). Светлеют сгустки,
 * а не полоса целиком.
 *
 * После уменьшения граней кубмапы до 3000² минификация на экране упала до
 * 1.35× (была 2.7×), но значения не пересматривались: GPU сэмплирует ту же
 * пару мип-уровней 3000/1500 с тем же весом блендинга — log₂(2.7) ≈ 1.43 при
 * базе 6000 и log₂(1.35) ≈ 0.43 при базе 3000, уровень сместился на единицу
 * вместе с базой, а дробная часть (вес) не изменилась. Прямая сверка кадров
 * «до/после» на новых гранях в одной позе камеры это подтвердила: средняя
 * яркость области полосы Млечного Пути 34.4 → 34.7, пикселей ярче 200 в ней
 * 232 → 231 — картинка на экране не изменилась.
 */
export const background: BackgroundConfig = {
  background: {
    highlightThreshold: 0.4,
    highlightBoost: 9
  }
}
