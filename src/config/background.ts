/** Источник неба: каталожное небо Брунетона или прежняя кубмапа сценария */
export type BackgroundSource = 'gaia' | 'cubemap'

/**
 * Источник из окружения сборки (VITE_SKY_SOURCE): тайлы Gaia лежат только
 * локально, публичное демо собирается на кубмапе (deploy.yml)
 */
export function resolveBackgroundSource(value: string | undefined): BackgroundSource {
  return value === 'cubemap' ? 'cubemap' : 'gaia'
}

/**
 * Конфиг фона сцены. Кубмапа восьмибитная: без подъёма (gain = 1) самая яркая
 * звезда в ней равна 1.0. С подъёмом ВЕСЬ сигнал (после вычитания пьедестала)
 * умножается на gain ещё до расширения хайлайтов и способен сам пробить порог
 * блума (BLOOM_OPTIONS.luminanceThreshold) — точку пересечения с 1.0 теперь
 * задаёт gain, а не highlightThreshold. Нетронутой подъёмом остаётся только
 * исходная выборка raw, по которой расширение меряет порог (см. докблок
 * `sampleSkyboxHdr`), а не то, что в итоге летит в кадр.
 */
export interface BackgroundConfig {
  background: {
    /** Из VITE_SKY_SOURCE, смена — пересборкой; грузится только выбранный источник */
    source: BackgroundSource
    gaia: {
      /** Сдвиг яркости неба Gaia в стопах; пропорции звёзд и полосы — из данных */
      exposureStops: number
      /**
       * Мягкий потолок яркости неба в единицах кадра (порог блума — 1.0):
       * выше — логарифм. Держит ярчайшие звёзды ниже порога заметных призраков
       */
      starCeiling: number
    }
    /** Только для source 'cubemap'. Ниже этого значения фон не меняется вовсе */
    highlightThreshold: number
    /** Во сколько раз растягивается превышение порога; 1 — расширение выключено */
    highlightBoost: number
    /**
     * Пьедестал пустого неба в ЛИНЕЙНОМ свете, вычитается перед подъёмом.
     * 0.000303 — это уровень 1 из 255 после sRGB-декода (1/255 / 12.92).
     */
    floor: number
    /** Множитель яркости фона после вычитания; 1 — подъём выключен */
    gain: number
  }
}

/**
 * Порог мерить надо ПОСЛЕ фильтрации, а не по текселям текстуры: грань кубмапы
 * приходит на экран уменьшенной, ядро звезды усредняется с соседями, и до
 * расширения доживает уже не 1.0. Отсюда 0.4, а не «почти единица» — при 0.8
 * расширение не меняло картинку вовсе.
 *
 * Порог задевает около 0.04% пикселей неба: ядра ярчайших звёзд и самые
 * светлые сгустки Млечного Пути. Полоса целиком не светлеет.
 *
 * Подъём фона: без него нижняя треть шкалы уходит в подошву AgX, и от
 * Млечного Пути остаётся только ядро. Оба числа — замеры, а не подбор вида.
 * Пьедестал: 79–99% пикселей каждой грани стоят на уровнях 0–1, полоса
 * начинается с 2, поэтому вычитание единицы отделяет космос от полосы.
 * Множитель: на 3 картинка чистая, на 5 в переходной зоне вылезают ступеньки
 * и хроматические пятна — это граница сверху, дальше упирается не кривая, а
 * восьмибитный исходник.
 */
export const background: BackgroundConfig = {
  background: {
    source: resolveBackgroundSource(import.meta.env.VITE_SKY_SOURCE),
    gaia: {
      // Замер 2026-10-10: полоса (среднее p90–p99 по небу) = прежней кубмапе после подъёма
      exposureStops: -5,
      // Замер 2026-10-10: поток ячейки Сириуса в 1080p ≤ 64 px·яркость при любом
      // субпиксельном сдвиге — призрак ≤ 1/10 калиброванного
      starCeiling: 19
    },
    highlightThreshold: 0.4,
    highlightBoost: 9,
    floor: 0.000303,
    gain: 3
  }
}
