/**
 * Рассеяние света кольцом. Одна фазовая функция на обе стороны: узкий лепесток
 * вперёд даёт свечение на просвет, широкий назад — подсветку со стороны звезды.
 *
 * Значения — стартовая точка, посчитанная арифметически, а не замер на
 * картинке; приёмку по виду делает владелец.
 */
export interface RingConfig {
  ring: {
    /** Узость и сила лепестка вперёд; при 0.6 пик примерно вдесятеро выше изотропного */
    forwardScattering: number
    /** Вес обратного лепестка: яркость кольца со стороны звезды */
    oppositionSurge: number
    /**
     * Как быстро гаснут плотные участки на просвет. 0 выключает инверсию
     * целиком: прошедший свет перестаёт зависеть от плотности.
     */
    densityExtinction: number
  }
}

export const ring: RingConfig = {
  ring: {
    forwardScattering: 0.6,
    oppositionSurge: 0.5,
    densityExtinction: 3
  }
}
