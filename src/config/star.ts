/**
 * Звезда: переключение LOD диск ↔ билборд-импостор, свечение издалека.
 *
 * Яркость импостора ручки не имеет НАМЕРЕННО: билборд считает поверхность
 * формулами диска (общий чанк starSurface, общие константы в helpers), и
 * любой множитель поверх воссоздал бы шов на переключении. Видимый размер
 * импостора (STAR_IMPOSTOR_PIXELS = 12) живёт в core/helpers/apparentSize.ts
 * и в конфиг не выносится по той же причине: по нему сведён стык LOD.
 * Свечение издалека — не такая ручка: множитель общий у обоих уровней
 * (StarLod.glowGain), стык он не разводит.
 */
export interface StarConfig {
  star: {
    /**
     * Гистерезис LOD — доля дистанции переключения (LOD.addLevel, third arg).
     * Диск → билборд на дистанции d, обратно — на d·(1−h): при возврате диск
     * появляется на 12/(1−h) px вместо 12. При 0.05 это ~12.6px
     * (неразличимо). У чёрной дыры 0.3 — там стык не сведён по размеру;
     * здесь крупное значение дало бы видимый скачок (~17px).
     */
    lodHysteresis: number
    /**
     * Множитель энергии звезды издалека (12 px и мельче) — им растёт гало
     * блума: дальше переключения LOD размер звезды заморожен, и другого
     * источника свечения у блума нет. 1 — выключено.
     *
     * Видит его не только блум: призраки блика объектива получают ту же
     * усиленную энергию и становятся ярче, источник анаморфного штриха
     * упирается в lensFlare.streakSourceCeiling.
     * Ядро диска уходит в белое (AgX).
     */
    farGlowGain: number
    /**
     * Видимый диаметр диска в пикселях, с которого множитель равен 1. Между
     * 12 px и этим порогом — плавный спад; крупный диск не трогается.
     * Обязан быть больше 12, иначе спада нет, только ступенька.
     */
    farGlowFadePixels: number
  }
}

/** farGlowGain и farGlowFadePixels стартовые, не замер — приёмка за владельцем */
export const star: StarConfig = {
  star: {
    lodHysteresis: 0.05,
    farGlowGain: 3,
    farGlowFadePixels: 48
  }
}
