/**
 * Блик объектива. Эффект чисто экранный: он видит яркие пиксели кадра и рисует
 * для них артефакты, ничего не зная об источниках света — как блум. Позиция
 * звезды в расчёте не участвует и участвовать не должна.
 *
 * Свечением вокруг ярких пикселей владеет `BloomEffect` (`BLOOM_OPTIONS`);
 * здесь только артефакты объектива: призраки и гало.
 */
export interface LensFlareConfig {
  lensFlare: {
    /** Общий множитель артефактов в кадре */
    intensity: number
    /** Сила призраков — зеркальных отражений ярких пикселей через центр кадра */
    ghostAmount: number
    /** Сила гало — кольца вокруг центра кадра */
    haloAmount: number
    /** Разведение каналов в гало, в текселях половинного разрешения */
    chromaticAberration: number
    /** Сила лучей объектива; 0 — маска тождественна и лучей нет */
    starburstAmount: number
    /** Сила анаморфного штриха; 0 — штриха нет */
    streakAmount: number
    /** Оттенок штриха; классический анаморфный блик холодный */
    streakTint: readonly [number, number, number]
  }
}

/**
 * Значения подобраны на приёмке 02.08.2026 замером, а не на глаз.
 *
 * Потолок задаёт НЕ солнечная система, а сцена чёрной дыры: там ярче порога
 * почти весь кадр, и призраки зеркалят диск сам в себя. При `intensity = 3`
 * тень дыры заливается молочной пеленой с цветными разводами; при 0.5 тень
 * остаётся чистой, а от гало остаются аккуратные радужные дуги по краям кадра.
 * Поэтому 0.5 — не «поосторожничал», а верхняя граница, за которой ломается
 * самая яркая сцена движка.
 *
 * В широком виде солнечной системы на этом значении эффект деликатен: сверка
 * кадров «до/после» в одной позе камеры даёт среднюю разность 1.45 из 255,
 * изменено 86 тысяч пикселей из миллиона с небольшим (92% из них стали ярче),
 * а сильнее чем на 20 изменились всего 30 пикселей, максимум 41 — у самого
 * солнца. То есть добавляется мягкое широкое свечение и кольцо гало, а не
 * резкие пятна.
 *
 * Прежнее значение было 0.01: при нём вклад эффекта не виден вовсе, что и
 * показал аудит — подъём в пятьдесят раз картинку почти не менял.
 */
export const lensFlare: LensFlareConfig = {
  lensFlare: {
    intensity: 0.5,
    ghostAmount: 0.25,
    haloAmount: 0.06,
    chromaticAberration: 10,
    starburstAmount: 1.5,
    streakAmount: 1.0,
    streakTint: [0.6, 0.8, 1.0]
  }
}
