/**
 * Блик объектива — анаморфный характер. Эффект экранный: рисует артефакты по
 * ярким пикселям кадра, ничего не зная об источниках света — как блум.
 *
 * Свечением вокруг ярких пикселей владеет `BloomEffect` (`BLOOM_OPTIONS`),
 * здесь только артефакты объектива: призраки (мягкие вертикальные овалы,
 * таблица — `flareGhosts.ts`) и анаморфный штрих.
 */
export interface LensFlareConfig {
  lensFlare: {
    /** Общий множитель всех артефактов в кадре */
    intensity: number
    /** Энергия призраков; доли потока — в таблице FLARE_GHOSTS. 0 — призраков нет */
    ghostAmount: number
    /** Показатель виньетирования призраков по положению источника; ≥ 0, 0 — без виньетирования */
    ghostVignette: number
    /** Разнос каналов призраков по оси: множитель разноса из таблицы, 0 — каналы совпадают; [0, 2], сеттер зажимает */
    ghostChromatic: number
    /**
     * Сила анаморфного штриха; 0 — штриха нет. Штрих стоит 129 выборок на
     * пиксель четверти разрешения плюс проход Kawase, готовящий его источник;
     * при нуле оба прохода пропускаются целиком.
     */
    streakAmount: number
    /**
     * Порог гейта штриха. Единицы — значения его источника (предразмытый буфер,
     * пониженный ядром Kawase MEDIUM), не яркость экрана и не порог блума.
     */
    streakThreshold: number
    /**
     * Шаг отсчётов в текселях источника штриха. Вылет полосы в экранных пикселях
     * равен `HALF_SAMPLES * streakScale * 2 / resolutionScale`: при штатных
     * `resolutionScale = 0.5` и `HALF_SAMPLES = 64` значение 5 даёт около 1280
     * пикселей в каждую сторону, то есть полосу через весь кадр.
     */
    streakScale: number
    /** Оттенок штриха; чем ближе к чистому синему, тем насыщеннее полоса */
    streakTint: readonly [number, number, number]
    /**
     * Потолок яркости ИСТОЧНИКА штриха. Единицы — значения того же буфера, что
     * меряет `streakThreshold`.
     *
     * Гейт штриха квадратичен по яркости: сумма для ровной области равна
     * примерно `L * (L - streakThreshold) * HALF_SAMPLES`, и предел half-float
     * достигается около `L = 31`. Ориентиры: звезда около 10, номинальный диск
     * чёрной дыры около 16, белый карлик 31–64. Ноль гасит штрих целиком.
     */
    streakSourceCeiling: number
  }
}

/**
 * Значения призраков стартовые, по расчёту (калибровка в flareGhosts.ts),
 * не замер — приёмка по виду за владельцем. Сила штриха и intensity выбраны
 * владельцем.
 */
export const lensFlare: LensFlareConfig = {
  lensFlare: {
    intensity: 0.1,
    ghostAmount: 1,
    ghostVignette: 2,
    ghostChromatic: 1,
    streakAmount: 0.005,
    streakThreshold: 0.3,
    streakScale: 5,
    streakTint: [0.15, 0.1, 1.0],
    streakSourceCeiling: 16
  }
}
