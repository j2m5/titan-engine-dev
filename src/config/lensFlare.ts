/**
 * Блик объектива. Эффект чисто экранный: он видит яркие пиксели кадра и рисует
 * для них артефакты, ничего не зная об источниках света — как блум. Позиция
 * звезды в расчёте не участвует и участвовать не должна.
 *
 * Свечением вокруг ярких пикселей владеет `BloomEffect` (`BLOOM_OPTIONS`);
 * здесь только артефакты объектива: призраки и гало.
 */
export interface LensFlareConfig {
  lensFlare: {
    /** Общий множитель артефактов в кадре */
    intensity: number
    /** Сила призраков — зеркальных отражений ярких пикселей через центр кадра */
    ghostAmount: number
    /** Сила гало — кольца вокруг центра кадра */
    haloAmount: number
    /** Разведение каналов в гало, в текселях половинного разрешения */
    chromaticAberration: number
    /** Сила лучей объектива; 0 — маска тождественна и лучей нет */
    starburstAmount: number
    /**
     * Порог, вычитаемый из каждой выборки призрака. Ожидаемый диапазон — от
     * нуля и выше; отрицательное значение не вычитает, а прибавляет.
     *
     * ЕДИНИЦЫ НЕ ЯРКОСТЬ ЭКРАНА. Вычитание идёт по значениям буфера, который
     * уже прошёл порог блума, даунсэмпл и предразмытие `KawaseBlurPass` с
     * `KernelSize.SMALL` (см. `LensFlareEffect.ts`) — то есть по HDR-величинам,
     * помноженным на smoothstep-множитель порога и сглаженным этим ядром.
     * Число не сопоставимо ни с `BLOOM_OPTIONS.luminanceThreshold`, ни с
     * яркостью пикселя на экране; осмысленный диапазон определяется только
     * замером, и смена `kernelSize` предразмытия требует перезамера
     */
    ghostThreshold: number
    /**
     * Показатель затухания призраков к краю кадра: больше — плотнее к центру.
     * Должен быть строго положительным — при основании `pow` равном 0 (угол
     * кадра, где спад зажат в 1) показатель 0 или отрицательный даёт
     * неопределённое поведение в GLSL
     */
    ghostAttenuation: number
    /**
     * Сила анаморфного штриха; 0 — штриха нет.
     *
     * НЕ ЗАМЕР, стартовая точка. Гейт штриха не ограничен сверху, а отсчётов
     * 129: сумма получается на два порядка выше, чем при прежних 33, поэтому
     * значение и упало с 5 до сотых. Крутить первым при жалобе «слишком
     * заметный»
     */
    streakAmount: number
    /**
     * Порог гейта штриха.
     *
     * ЕДИНИЦЫ НЕ ЯРКОСТЬ ЭКРАНА и не порог блума. Штрих читает собственный
     * источник — понижение предразмытого буфера до четверти разрешения ядром
     * Kawase MEDIUM, — и меряет значения именно этого буфера.
     *
     * НЕ ЗАМЕРЕН под текущий источник: 0.3 получено пробой, когда источником
     * был предразмытый буфер ПОЛОВИННОГО разрешения с ядром SMALL. Более
     * широкое ядро и понижение делают пики ниже, так что число стоит
     * перезамерить, если штрих полезет на тусклое или наоборот пропадёт
     */
    streakThreshold: number
    /**
     * Шаг отсчётов в текселях ИСТОЧНИКА штриха (четверть разрешения кадра).
     *
     * Вылет полосы в экранных пикселях равен `HALF_SAMPLES * streakScale * 4`,
     * то есть при 64 и 5 — около 1280 пикселей в каждую сторону: полоса
     * пересекает кадр целиком, как в референсе владельца. Крутить при жалобе
     * «слишком короткий» или «слишком длинный»
     */
    streakScale: number
    /**
     * Оттенок штриха.
     *
     * НЕ перенос из three: у узла там почти чистый синий `[0.1, 0, 1]`, и на
     * широкой полосе он читается насыщенно-фиолетовым. Референс владельца —
     * холодная обесцвеченная полоса, отсюда подмешанные красный и зелёный
     */
    streakTint: readonly [number, number, number]
  }
}

