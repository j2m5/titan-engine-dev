/**
 * Блик объектива. Эффект экранный: рисует артефакты по ярким пикселям кадра,
 * ничего не зная об источниках света — как блум.
 *
 * Свечением вокруг ярких пикселей владеет `BloomEffect` (`BLOOM_OPTIONS`), здесь
 * только артефакты объектива: призраки, гало, лучи и анаморфный штрих.
 */
export interface LensFlareConfig {
  lensFlare: {
    /** Общий множитель всех артефактов в кадре */
    intensity: number
    /** Сила призраков — отражений ярких пикселей через центр кадра */
    ghostAmount: number
    /** Сила гало — кольца вокруг центра кадра */
    haloAmount: number
    /** Разведение каналов в гало, в текселях половинного разрешения */
    chromaticAberration: number
    /** Сила лучей объектива; 0 — маска тождественна, лучей нет */
    starburstAmount: number
    /**
     * Порог, вычитаемый из каждой выборки призрака. Ожидается неотрицательным:
     * отрицательное значение прибавляет, а не вычитает.
     *
     * Единицы — не яркость экрана. Буфер к этой выборке уже прошёл порог блума,
     * даунсэмпл, предразмытие и локальный контраст, то есть содержит разности с
     * окрестностью. Смена `kernelSize` предразмытия или `LOCAL_CONTRAST_RADIUS`
     * обесценивает подобранное значение.
     */
    ghostThreshold: number
    /**
     * Затухание призраков к краю кадра: больше — плотнее к центру. Строго
     * положительное: в углу кадра основание `pow` равно нулю, а неположительный
     * показатель даёт там неопределённое поведение в GLSL.
     */
    ghostAttenuation: number
    /**
     * Сила анаморфного штриха; 0 — штриха нет. Штрих стоит 129 выборок на
     * пиксель четверти разрешения плюс проход Kawase, готовящий его источник;
     * при нуле оба прохода пропускаются целиком.
     */
    streakAmount: number
    /**
     * Порог гейта штриха. Единицы — значения его источника (предразмытый буфер,
     * пониженный ядром Kawase MEDIUM), не яркость экрана и не порог блума.
     */
    streakThreshold: number
    /**
     * Шаг отсчётов в текселях источника штриха. Вылет полосы в экранных пикселях
     * равен `HALF_SAMPLES * streakScale * 2 / resolutionScale`: при штатных
     * `resolutionScale = 0.5` и `HALF_SAMPLES = 64` значение 5 даёт около 1280
     * пикселей в каждую сторону, то есть полосу через весь кадр.
     */
    streakScale: number
    /** Оттенок штриха; чем ближе к чистому синему, тем насыщеннее полоса */
    streakTint: readonly [number, number, number]
    /**
     * Потолок яркости ИСТОЧНИКА штриха. Единицы — значения того же буфера, что
     * меряет `streakThreshold`.
     *
     * Существует потому, что гейт штриха квадратичен по яркости: сумма для
     * ровной области равна примерно `L * (L - streakThreshold) * HALF_SAMPLES`,
     * и предел half-float достигается уже около `L = 31`. За ним полоса теряет
     * затухание, идёт во весь кадр ровной яркостью и замазывает сам источник.
     *
     * Ориентиры сцен: обычная звезда даёт около 10, номинальный диск чёрной
     * дыры около 16, белый карлик — 31 (G29-38) и 64 (Sirius B, потолок HDR).
     * Значение 16 оставляет звезду и номинальный диск нетронутыми и уводит
     * карликов в линейный режим с запасом почти вчетверо до клэмпа.
     *
     * Ловушка: у чёрной дыры к диску домножается релятивистский `beaming`,
     * который на приближающейся стороне поднимает яркость выше номинала — там
     * потолок срабатывает и вид полосы меняется. Величина не измерена.
     *
     * Ноль гасит штрих целиком; очень большое значение возвращает поведение до
     * появления ручки.
     */
    streakSourceCeiling: number
  }
}

