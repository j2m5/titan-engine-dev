/**
 * Блик объектива. Эффект чисто экранный: он видит яркие пиксели кадра и рисует
 * для них артефакты, ничего не зная об источниках света — как блум. Позиция
 * звезды в расчёте не участвует и участвовать не должна.
 *
 * Свечением вокруг ярких пикселей владеет `BloomEffect` (`BLOOM_OPTIONS`);
 * здесь только артефакты объектива: призраки и гало.
 */
export interface LensFlareConfig {
  lensFlare: {
    /** Общий множитель артефактов в кадре */
    intensity: number
    /** Сила призраков — зеркальных отражений ярких пикселей через центр кадра */
    ghostAmount: number
    /** Сила гало — кольца вокруг центра кадра */
    haloAmount: number
    /** Разведение каналов в гало, в текселях половинного разрешения */
    chromaticAberration: number
    /** Сила лучей объектива; 0 — маска тождественна и лучей нет */
    starburstAmount: number
    /** Сила анаморфного штриха; 0 — штриха нет */
    streakAmount: number
    /** Оттенок штриха; классический анаморфный блик холодный */
    streakTint: readonly [number, number, number]
  }
}

/**
 * Значения подобраны на приёмке 02.08.2026 по замерам и по правке владельца:
 * блик обязан быть ненавязчивым, а из артефактов вперёд выходит анаморфный
 * штрих — тонкая холодная черта (референс: блики Mass Effect).
 *
 * Потолок задаёт НЕ солнечная система, а сцена чёрной дыры: там ярче порога
 * почти весь кадр, и артефакты зеркалят диск сам в себя. Замеренные границы:
 * при `intensity = 3` тень дыры заливается молочной пеленой с цветными
 * разводами; при `streakAmount = 8` тень получает синий налёт от штриха и
 * перестаёт быть коричневой. Выбранные 0.15 и 3 стоят НИЖЕ этих границ —
 * с запасом в двадцать и в два с половиной раза: владелец правил в сторону
 * ненавязчивости, а не в упор к пределу.
 *
 * Разделение ролей: `intensity` держит общий уровень низким, а `streakAmount`
 * поднимает ОДИН артефакт, который владелец хочет видеть. Призраки и гало на
 * этих числах дают лишь намёк (0.15 × 0.2 и 0.15 × 0.04).
 *
 * Оттенок штриха умножается на ЯРКОСТЬ источника, а не на его цвет: синева
 * принадлежит просветлению линзы, а не звезде. Иначе тёплое солнце съедало
 * холодный оттенок, и черта выходила грязно-серой (проверено замером: было
 * (20,19,17), то есть краснее фона).
 *
 * Прежнее значение `intensity` было 0.01: при нём вклад эффекта не виден
 * вовсе — подъём в пятьдесят раз картинку почти не менял.
 */
export const lensFlare: LensFlareConfig = {
  lensFlare: {
    intensity: 0.15,
    ghostAmount: 0.2,
    haloAmount: 0.04,
    chromaticAberration: 10,
    starburstAmount: 1.0,
    streakAmount: 3,
    streakTint: [0.3, 0.55, 1.0]
  }
}
