/**
 * Цвет и тон. Экспозиция и баланс белого применяются в линейном свете до
 * кривой тонмаппинга, остальное — после неё.
 *
 * Фотографичная настройка: лёгкий контраст, исходная насыщенность,
 * нейтральные тени и света. Полностью нейтральный контраст — 1.
 */
export interface GradingConfig {
  grading: {
    /** Сдвиг экспозиции в стопах; 0 — нейтраль, один стоп вдвое ярче */
    exposure: number
    /**
     * Температура ОПОРНОГО СВЕТА в Кельвинах, а не картинки: ниже опорных
     * 6500 кадр становится холоднее, выше — теплее. Рабочий диапазон
     * 2000–40000 K, значения за границами зажимаются (`whiteBalance.ts`).
     */
    temperature: number
    /** Зелёный–пурпурный, вторая ось баланса белого; диапазон −1…1 */
    tint: number
    /** Контраст вокруг опорной точки 0.5 экранной шкалы (128/255); 1 — нейтраль */
    contrast: number
    /** Насыщенность относительно яркости; 1 — нейтраль, 0 — серый кадр */
    saturation: number
    /** Оттенок, к которому поднимаются тени (нижняя половина экранной шкалы) */
    shadowTint: readonly [number, number, number]
    /** Сила подъёма теней, аддитивная; 0 — тени не трогаются */
    shadowLift: number
    /** Оттенок светов (верхняя половина экранной шкалы) */
    highlightTint: readonly [number, number, number]
    /** Сила тонировки светов, множительная; 0 — света не трогаются */
    highlightGain: number
  }
}

export const grading: GradingConfig = {
  grading: {
    exposure: 0,
    temperature: 6500,
    tint: 0,
    contrast: 1.02,
    saturation: 1,
    shadowTint: [0.35, 0.45, 1.0],
    shadowLift: 0,
    highlightTint: [1.0, 0.92, 0.82],
    highlightGain: 0
  }
}
