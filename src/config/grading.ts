/**
 * Цвет и тон. Экспозиция и баланс белого применяются в линейном свете до
 * кривой тонмаппинга, остальное — после неё.
 *
 * Значения контраста, насыщенности и тонировки — СТАРТОВАЯ ТОЧКА, подобранная
 * арифметически, а не замер: приёмка по картинке за владельцем. Вернуть
 * нейтраль можно без правок кода — контраст и насыщенность в 1, обе силы
 * тонировки в 0.
 */
export interface GradingConfig {
  grading: {
    /** Сдвиг экспозиции в стопах; 0 — нейтраль, один стоп вдвое ярче */
    exposure: number
    /**
     * Температура ОПОРНОГО СВЕТА в Кельвинах, а не картинки: ниже опорных
     * 6500 кадр становится холоднее, выше — теплее. Рабочий диапазон
     * 2000–40000 K, значения за границами зажимаются (`whiteBalance.ts`).
     */
    temperature: number
    /** Зелёный–пурпурный, вторая ось баланса белого; диапазон −1…1 */
    tint: number
    /** Контраст вокруг опорной точки 0.5; 1 — нейтраль */
    contrast: number
    /** Насыщенность относительно яркости; 1 — нейтраль, 0 — серый кадр */
    saturation: number
    /** Оттенок, к которому поднимаются тени */
    shadowTint: readonly [number, number, number]
    /** Сила подъёма теней; 0 — тени не трогаются */
    shadowLift: number
    /** Оттенок светов */
    highlightTint: readonly [number, number, number]
    /** Сила тонировки светов; 0 — света не трогаются */
    highlightGain: number
  }
}

