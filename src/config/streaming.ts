/**
 * Бюджет стриминга текстур (TextureBudget): сколько видеопамяти движок
 * готов отдать под карты акторов.
 */
export interface StreamingConfig {
  streaming: {
    /**
     * Бюджет самоназначенный — WebGL не умеет спрашивать, сколько видеопамяти
     * реально занято на карте. 2048 (2 ГиБ) рискует на нижнем грейде видеопамяти
     * современных карт, но послойный приоритет (см. decideStreaming) деградирует
     * мягко: при нехватке гаснут младшие слои дальних тел, а не сами тела целиком.
     * Прежний консерватизм 1 ГиБ защищал от худшей механики — единицей стриминга
     * тогда был актор целиком, и переполнение бюджета роняло тело без карты.
     * Актуальные худшие группы соседей (см. Texture Budget Neighbours): Сатурн
     * 2652 МиБ, Юпитер 1877 МиБ; Земля+Луна 939 МиБ — исторический бенчмарк
     * с эпохи единицы-актора, приведён для масштаба.
     */
    textureBudgetMiB: number
    /**
     * Порог отсечки кандидатов по угловому размеру: диаметр тела на экране
     * в пикселях, ниже которого его карты незачем стримить вовсе — тело
     * субпиксельно, плейсхолдер неотличим от честной текстуры глазом.
     *
     * Без отсечки `collectCandidates` разворачивает КАЖДОЕ наблюдаемое тело
     * сцены в кандидатов — при послойной жадной политике (decideStreaming)
     * слой ДИФФУЗОВ ВСЕЙ СЦЕНЫ (сотни тел, ранг 0) обгоняет slope/detail
     * БЛИЖНЕГО тела по построению: диффузы дальних субпиксельных тел жадно
     * съедают бюджет раньше, чем очередь доходит до рельефа/детали того, что
     * реально видно. Замерено на приёмке: слой диффузов всей сцены 6135 МиБ
     * при бюджете 2048 — регрессия «тайлы на поверхностях планет пропали».
     *
     * Перевод в порог `actorPriority` — см. `minBodyPixelsToPriorityThreshold`
     * (src/core/streaming/angularCutoff.ts).
     *
     * 4 — диаметр примерно на грани заметности: тело меньше уже не читается
     * как диск, только как точка, текстура ему без надобности.
     */
    minBodyPixels: number
    /**
     * Период принудительного пересчёта дистанций и состава видеопамяти, мс.
     *
     * Событие `change` от контролов возникает только когда движется КАМЕРА, а
     * тела движутся по орбитам сами: при неподвижной камере подходящее тело не
     * становилось кандидатом стриминга никогда, а перерасход бюджета не
     * рассасывался до следующего шевеления мышью.
     *
     * 500 мс: полный пересчёт замерен в 0.63 мс, то есть ~0.1% времени. При
     * движущейся камере пересчёт и так идёт каждый кадр — тик ничего не
     * ухудшает, он закрывает ровно случай неподвижной камеры. Интервал —
     * стенные часы, поэтому ускорение времени симуляции на него не влияет.
     */
    recomputeIntervalMs: number
  }
}

export const streaming: StreamingConfig = {
  streaming: {
    textureBudgetMiB: 2048,
    minBodyPixels: 4,
    recomputeIntervalMs: 500
  }
}
