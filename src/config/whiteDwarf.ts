/**
 * Белый карлик: переключение LOD и ореол.
 *
 * Яркости импостора ручки нет НАМЕРЕННО — билборд зовёт тот же wdShade из
 * чанка whiteDwarfSurface, что и диск; любой множитель поверх воссоздал бы шов
 * на переключении (тот же контракт, что у config/star.ts и config/brownDwarf.ts).
 */
export interface WhiteDwarfConfig {
  whiteDwarf: {
    /** Гистерезис LOD — доля дистанции переключения (см. star.lodHysteresis) */
    lodHysteresis: number
    /**
     * Прозрачность спрайта-ореола (StarInnerLayer). Выше звёздных 0.03: у
     * карлика поверхностная яркость в видимой полосе в десятки раз больше
     * солнечной, а угловой размер в сотню раз меньше — на всех практических
     * дистанциях это точка, и ореол несёт весь её вид. Ноль гасит слой.
     */
    haloOpacity: number
    /**
     * Масштаб спрайта-ореола относительно звёздного. Меньше единицы: ореол
     * карлика обязан читаться как жёсткая искра, а не как раздутая корона —
     * короны у карлика нет физически (H/R ~ 3e-5).
     */
    haloScale: number
  }
}

export const whiteDwarf: WhiteDwarfConfig = {
  whiteDwarf: {
    lodHysteresis: 0.05,
    haloOpacity: 0.05,
    haloScale: 0.45
  }
}
