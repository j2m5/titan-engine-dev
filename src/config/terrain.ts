/**
 * SSE-отбор квадродерева рельефа (selectTerrainNodes): пороги гистерезиса
 * сплита/мержа узла в пикселях экранной ошибки.
 */
export interface TerrainConfig {
  terrain: {
    /**
     * Узел спускается глубже, когда его SSE превышает это число пикселей
     * (обозначается τ в замерах). Рабочий диапазон: τ=6 (дефолт) — быстрый
     * профиль, на орбите грубее статической кубосферы 3а (втрое по ε),
     * максимум FPS; τ≈2 — визуальный паритет с 3а на орбите; ниже 1.5 не
     * рекомендуется — на 4K желаемый набор упирается в потолок пула
     * (MAX_LIVE_PATCHES, см. TerrainPatchPool).
     */
    sseSplitPixels: number
    /**
     * Доля sseSplitPixels — порог схлопывания уже разбитого узла ниже
     * sseSplitPixels·sseMergeFactor. Меньше 1: гистерезис против дрожания
     * на границе порога кадр к кадру.
     */
    sseMergeFactor: number
    /**
     * Видимый диаметр тела в пикселях, при котором запрашивается его карта
     * высот. Много выше порога, на котором LOD меняет билборд на настоящий
     * меш (distanceLod(3) в RenderableFactory, ~3–4 px): карта успевает
     * доехать до того, как тело станет мешем.
     */
    heightMapLoadPixels: number
    /**
     * Видимый диаметр, ниже которого карта освобождается. Разрыв с
     * heightMapLoadPixels — гистерезис против качания 64 МиБ на границе.
     */
    heightMapReleasePixels: number
    /**
     * Потолок JS-heap под резидентные карты высот, МиБ. Пороги выше решают
     * «пора ли», этот — «во что обойдётся»: без него реестр рос ровно
     * настолько, насколько тел окажется рядом (ревью 2026-08-20, находка №7).
     *
     * Бюджет считает обе копии карты: главного потока и воркера (карта и aux,
     * см. `TerrainPatchBuilder.mapCopies`; без воркера копия одна). 512 МиБ при
     * двух копиях — прежние 256 по картам: четыре карты предельного размера
     * (8192×4096 = 64 МиБ) против 788 МиБ, которых стоила жадная загрузка
     * всего сценария. Производные структуры воркера (сетка огибающей и т.п.)
     * не считаются. Фактическая
     * потребность на порядок скромнее: выше порога загрузки одновременно
     * бывают единицы тел. Потолок мягкий в одну сторону — самая приоритетная
     * карта резидентна всегда, даже если одна дороже всего бюджета
     * (см. `decideHeightMaps`), иначе тело, к которому подлетели, осталось бы
     * без рельефа именно из-за размера своей карты.
     */
    heightMapBudgetMiB: number
    /** Длина луча марша тени рельефа к солнцу, км: на терминаторе тени десятки км, 150 с запасом при 20 шагах. */
    shadowMaxKm: number
    /** Ближний слой тени: плитка высот вокруг подспутниковой точки камеры. */
    nearShadow: {
      /** Текселей по стороне плитки (R32F). */
      tileTexels: number
      /** Тексель плитки, м; окно = tileTexels · texelMeters. */
      texelMeters: number
      /** Длина луча ближнего марша к солнцу, м. */
      maxDistanceMeters: number
      /** Высота камеры над поверхностью, м: выше — плитки нет. */
      maxAltitudeMeters: number
      /** Высота камеры, м, с которой вес слоя спадает к нулю на maxAltitudeMeters. */
      fadeAltitudeMeters: number
      /**
       * Перепечка при сдвиге подспутниковой точки дальше этой доли стороны плитки.
       * Инвариант: fadeEndMeters + rebakeFraction · сторона ≤ 0.8 · полуширины —
       * окно камеры не доходит до страховки края, пока центр плитки отстаёт.
       */
      rebakeFraction: number
      /**
       * Вес слоя по расстоянию от текущей подкамерной точки, м: 1 ближе fadeStart,
       * 0 дальше fadeEnd. Окно едет с камерой, а не прыгает с центром плитки на
       * перепечке — иначе полоса теней моргает.
       */
      fadeStartMeters: number
      fadeEndMeters: number
    }
    lod: {
      /**
       * Бюджет на постройки патчей за кадр (TerrainPatchGroup.updateObject), мс.
       * Гейтит только СТАРТ следующей постройки — сама постройка атомарна
       * (прервать её серединой нельзя), бюджет не ограничивает её длительность.
       * Очередь построена coarse-first, минимум одна постройка происходит
       * всегда (иначе на слабом CPU дыры не закрываются никогда), дальше цикл
       * идёт, пока не исчерпан бюджет. Дефолт 6 — у самой поверхности (суб-
       * текселя детали, глубина у L8) одна постройка стоит сопоставимо с
       * бюджетом или выше, там цикл обычно и укладывается в одну постройку за
       * кадр.
       *
       * С полосой средней полосы B (Task 5, фикс-раунд 2): один патч L8 у
       * поверхности стоит 7-9 мс (замер на реальной карте Луны,
       * midbandBuildBudget.spec) — ДОРОЖЕ самого бюджета 6 мс. Цикл
       * заканчивается сразу после гарантированной первой постройки («минимум
       * одна» срабатывает почти всегда), ручка фактически перестала быть
       * «сколько построек за кадр» и стала «сколько СВЕРХ одной гарантированной» —
       * у поверхности с полосой это обычно 0.
       *
       * Бюджет принадлежит СИНХРОННОМУ строителю (тесты, вода, фолбэк без
       * Worker) — только там запрос патча и есть сама постройка на этом
       * потоке. У воркерного строителя запрос дёшев, кадр он не тратит, и
       * очередь правит buildInFlight, а не этот бюджет.
       */
      patchBuildBudgetMs: number
      /**
       * Потолок запросов постройки в полёте на группу (воркер): ≈1 патч/8 мс
       * → 6 в полёте ≈ 50 мс латентности сплита.
       */
      buildInFlight: number
      /**
       * Длительность геоморфа патча, с реального времени кадра: дети сплита
       * спадают из родительской формы в свою, дети мержа растут в родительскую
       * до свопа. 0 — морф выключен, своп мгновенный.
       */
      morphSeconds: number
    }
  }
}

