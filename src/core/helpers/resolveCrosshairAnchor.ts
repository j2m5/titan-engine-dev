import { Object3D } from 'three'

/**
 * Поднимает якорь прицела вверх по цепочке кликабельных родителей: патч
 * кубосферы → группа TerrainSphere. LOD переключает видимость ЦЕЛЫХ уровней
 * (TerrainSphere целиком), а не отдельных патчей — крестик, подвешенный на
 * патче или на самой группе, гаснет вместе с ней при переключении дальности.
 * Якорь — родитель верхней кликабельной группы (обычно LOD, он видим всегда),
 * туда и садится прицел.
 *
 * Для объектов без кликабельного родителя (легаси Planet и прочие тела,
 * кликабельные напрямую под LOD/узлом) цикл не делает ни шага — поведение
 * байт-в-байт прежнее: якорь — сам пересечённый объект.
 */
export function resolveCrosshairAnchor(object: Object3D): Object3D {
  let anchor = object

  while (anchor.parent && anchor.parent.userData.clickable === true) anchor = anchor.parent

  return anchor
}
