/**
 * Формулы поверхности белого карлика, общие для диска и билборда-импостора.
 *
 * Уникальность объекта в том, что рисовать на поверхности НЕЧЕГО, и это физика,
 * а не упрощение: у горячих (T > 12 kK) атмосфера радиативная, конвекции нет
 * вовсе; у холодных гранула порядка километра при радиусе 5850 км, то есть
 * 1/6000 диска — не разрешится никогда. Шума здесь нет намеренно, добавлять его
 * значит рисовать заведомо несуществующее.
 *
 * Зависимостей от других чанков нет: ни snoise, ни starSurface не нужны.
 *
 * CPU-зеркало: tests/whiteDwarf/whiteDwarfSurfaceMirror.ts — менять строго
 * синхронно, GLSL обязан повторять его один в один.
 */


export const whiteDwarfSurface = `
  // Оптическая глубина выхода излучения в приближении Эддингтона
  #define WD_EDDINGTON_TAU 0.66666667
  // Потолок HDR ВДВОЕ ниже звёздных 64, и это не косметика.
  //
  // У звезды и коричневого карлика 64 — предохранитель: они дают около 10 и до
  // него не достают никогда. У белого карлика это рабочая величина, в которую
  // тело упирается всей поверхностью, и она попадает на вход блума с порогом 1
  // при девяти мипах, радиусе 0.95 и SCREEN-смешивании. Источник на 64 несёт
  // 63 единицы над порогом против 9 у звезды — всемеро больше энергии, и кадр
  // рядом с карликом заливало белым.
  //
  // Опускать ОДИН лишь exposureBias бесполезно: у горячего карлика каналы
  // клипаются здесь, и половинная экспозиция роняет яркость всего на 15%.
  // Потолок обязан идти вниз вместе с ней — см. WHITE_DWARF_DISPLAY_SCALE.
  #define WD_HDR_CEILING 32.0

  /**
   * Лимбовое потемнение из первых принципов, без подгоночных коэффициентов.
   *
   * Серая атмосфера даёт T^4(tau) = 0.75 * Teff^4 * (tau + 2/3), а соотношение
   * Эддингтона-Барбье — что под углом mu наружу выходит планковская функция,
   * взятая на глубине tau = mu. Отсюда отношение яркостей есть отношение
   * планковских функций на двух температурах.
   *
   * planckX — безразмерное hc/(lambda * k * Teff) по каналам R/G/B, считается на
   * CPU (planckX в shaders/lib/helpers.ts). Именно он несёт зависимость и от
   * температуры, и от длины волны: у горячего карлика в видимом x мал (режим
   * Рэлея-Джинса, B почти линейна по T) и диск выходит ПЛОСКИМ, у холодной
   * звезды x велик (режим Вина) и потемнение сильное. Тройка-константа
   * STAR_LIMB_COEFF этого не умеет — она зашита под одну температуру.
   *
   * sOne считается тем же выражением, что sMu, а не отдельной константой:
   * иначе при mu = 1 числитель и знаменатель разойдутся в последнем бите и
   * центр диска перестанет быть ровно единицей.
   *
   * Предел при planckX -> 0 равен s(0)/s(1) = 0.795, а не нулю: даже в чистом
   * Рэлее-Джинсе остаётся потемнение от самого перепада температуры. Нуля
   * здесь быть не может, и деление безопасно при любом planckX > 0.
   */
  vec3 wdLimb(float mu, vec3 planckX) {
    float m = clamp(mu, 0.0, 1.0);
    float sMu = pow(0.75 * (m + WD_EDDINGTON_TAU), 0.25);
    float sOne = pow(0.75 * (1.0 + WD_EDDINGTON_TAU), 0.25);

    return (exp(planckX / sOne) - 1.0) / (exp(planckX / sMu) - 1.0);
  }

  /**
   * Единственная точка композиции тела — её и зовут оба LOD одним и тем же
   * списком аргументов (инвариант закреплён тестом WhiteDwarfImpostor.spec).
   *
   * intensity приходит уже посчитанной из температуры на CPU как отношение
   * планковских функций в видимой полосе, а НЕ как T^4: болометрическая
   * четвёртая степень у карлика почти вся уходит в EUV, которого камера не
   * видит, и дала бы завышение на порядок.
   */
  vec3 wdShade(float mu, vec3 baseColor, vec3 planckX, float intensity) {
    return min(baseColor * intensity * wdLimb(mu, planckX), vec3(WD_HDR_CEILING));
  }
`
