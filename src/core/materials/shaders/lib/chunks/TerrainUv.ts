/**
 * UV из body-локального направления для терраформных тел — попиксельно, не
 * по вершинному vUv (тот вырождается у полюсов кубосферы, см. вызывающих).
 * Общий кусок для PlanetShaderTemplate (суша) и WaterShaderTemplate (канал A
 * запечённой глубины воды — та же slope-карта, тот же путь текстуры): оба
 * обязаны сэмплировать по ОДНОМУ uv, иначе береговая линия воды разъедется с
 * береговой линией суши на один и тот же тексель по-разному.
 *
 * Конвенция — CPU-канон TerrainHeightField.dirToUv: phi = atan(z, −x),
 * u = phi/2π (+1 при отрицательном скачок производной совпадает со швом
 * текстуры). Текстурное v = 1 − v карты: dirToUv отдаёт v в координатах
 * карты (строка 0 = север), загрузчик текстур флипует изображение при
 * загрузке (север = v 1) — без флипа рельеф/вода зеркалились бы по С-Ю.
 *
 * Двухдоменный выбор u (seamless equirect): fract(uRaw) рвёт производную на
 * шве текстуры (u=0/1), сдвинутый вариант — на противоположном меридиане;
 * берём в каждом пикселе домен с меньшей fwidth. Без этого один непрерывный
 * по значению u (простой +1 при отрицательном) даёт скачок ЭКРАННОЙ
 * ПРОИЗВОДНОЙ ~1 на шве — GPU берёт грубейший мип и на этой колонке
 * пикселей рисует полосу мыла.
 */
export const terrainUvFunctions = `
  vec2 terrainUv(vec3 dirLocal) {
    float phi = atan(dirLocal.z, -dirLocal.x);
    float uRaw = phi / 6.28318530717958647692;
    float u1 = fract(uRaw);
    float u2 = fract(uRaw + 0.5) - 0.5;
    float u = fwidth(u1) <= fwidth(u2) ? u1 : u2;

    return vec2(u, 1.0 - acos(clamp(dirLocal.y, -1.0, 1.0)) / 3.14159265358979323846);
  }
`
