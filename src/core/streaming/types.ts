/** Актор-кандидат на стриминг вместе с текущим приоритетом. */
export interface StreamCandidate {
  actorId: number
  /** Имя актора: по нему рендерабл ищется в графе сцены. */
  name: string
  /**
   * Радиус, делённый на расстояние до камеры.
   *
   * Монотонно связано с угловым размером на экране, то есть с числом пикселей,
   * которые займёт текстура. Расстояние до камеры само по себе не годится:
   * Сатурн, наблюдаемый с Мимаса, дальше Мимаса, но занимает пол-неба.
   */
  priority: number
  /** Пути стримируемых ресурсов этого актора. Ключи реестра текстур. */
  paths: string[]
}

/** Что загрузить и что вытеснить по итогам одного решения. */
export interface StreamDecision {
  load: StreamCandidate[]
  evict: StreamCandidate[]
  /**
   * Кто заслуживает резидентности по приоритету и бюджету САМ ПО СЕБЕ.
   * Исключённые кандидаты не заряжают бюджет вовсе (см. `decideStreaming`),
   * поэтому `wanted` не «как если бы `excluded` не существовало» — она
   * строго щедрее гипотетического прохода, заряжающего всех подряд:
   * исключённый освобождает соседям больше места, чем занял бы, реально
   * загрузившись. Направление безвредно для смысла поля («ещё заслуживает
   * резидентности») — оно лишь держит `attempted` дольше, а не снимает
   * блокировку раньше времени. Не эквивалентно «есть в `load`»: актор может
   * быть в `wanted`, но не в `load`, если он уже загружен или временно
   * исключён (проваленная попытка). Нужен вызывающему, чтобы отличить «ещё
   * в зоне приоритета, просто заблокирован» от «покинул зону» — то есть
   * решать, когда снять блокировку повторной попытки после провала.
   *
   * `load ⊆ wanted` — гарантия структурная (см. `decideStreaming`), не
   * зависящая от конкретных входных данных.
   *
   * `wanted` и `evict` гарантированно НЕ пересекаются, только пока
   * `loaded ∩ excluded = ∅` — то есть пока вызывающий код не считает один и
   * тот же actorId одновременно «уже резидентным» и «исключённым». Держать
   * это в порядке — обязанность вызывающего: `ResourceObserver` поддерживает
   * его тем, что переводит актора в исключённые (`attempted`) СИНХРОННО с
   * тем, как убирает его из `loaded`, при провале загрузки.
   */
  wanted: Set<number>
}
