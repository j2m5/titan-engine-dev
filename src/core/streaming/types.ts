/** Актор-кандидат на стриминг вместе с текущим приоритетом. */
export interface StreamCandidate {
  actorId: number
  /** Имя актора: по нему рендерабл ищется в графе сцены. */
  name: string
  /**
   * Радиус, делённый на расстояние до камеры.
   *
   * Монотонно связано с угловым размером на экране, то есть с числом пикселей,
   * которые займёт текстура. Расстояние до камеры само по себе не годится:
   * Сатурн, наблюдаемый с Мимаса, дальше Мимаса, но занимает пол-неба.
   */
  priority: number
  /** Пути стримируемых ресурсов этого актора. Ключи реестра текстур. */
  paths: string[]
}

/** Что загрузить и что вытеснить по итогам одного решения. */
export interface StreamDecision {
  load: StreamCandidate[]
  evict: StreamCandidate[]
  /**
   * Кто заслуживает резидентности по приоритету и бюджету сам по себе. Не то
   * же, что «есть в `load`»: актор может быть в `wanted`, но уже загружен или
   * временно исключён после провала. Поле нужно, чтобы отличить «ещё в зоне
   * приоритета, просто заблокирован» от «покинул зону» и решить, когда снимать
   * блокировку повторной попытки.
   *
   * `load ⊆ wanted` — структурная гарантия. `wanted` и `evict` не пересекаются,
   * только пока вызывающий код не считает один actorId одновременно
   * резидентным и исключённым.
   */
  wanted: Set<number>
}
