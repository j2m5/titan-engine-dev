// Project-owned periodic void-and-cluster ranking; run with Node, no dependencies.
// Algorithm background: https://momentsingraphics.de/BlueNoise.html
import { writeFile } from 'node:fs/promises'

const size = 64, count = size * size, sigma = 1.9, initialCount = Math.floor(count * 0.1)
let seed = 0x74697461
const random = () => {
  seed ^= seed << 13
  seed ^= seed >>> 17
  seed ^= seed << 5
  return (seed >>> 0) / 0x100000000
}
const kernel = Float64Array.from({ length: count }, (_, i) => {
  const x = Math.min(i % size, size - i % size), y = Math.min(Math.floor(i / size), size - Math.floor(i / size))
  return Math.exp(-(x * x + y * y) / (2 * sigma * sigma))
})
let occupied = new Uint8Array(count), energy = new Float64Array(count)
function update(point, delta) {
  const px = point % size, py = Math.floor(point / size)
  for (let i = 0; i < count; i++) {
    const x = (i % size - px + size) % size, y = (Math.floor(i / size) - py + size) % size
    energy[i] += delta * kernel[y * size + x]
  }
}
function choose(value, maximum) {
  let best = -1, score = maximum ? -Infinity : Infinity
  for (let i = 0; i < count; i++) if (occupied[i] === value && (maximum ? energy[i] > score : energy[i] < score)) {
    best = i
    score = energy[i]
  }
  if (best < 0) throw new Error('No ranking candidate')
  return best
}
const indices = Array.from({ length: count }, (_, i) => i)
for (let i = 0; i < initialCount; i++) {
  const next = i + Math.floor(random() * (count - i))
  ;[indices[i], indices[next]] = [indices[next], indices[i]]
  occupied[indices[i]] = 1
  update(indices[i], 1)
}
let iterations = 0
for (;;) {
  if (++iterations > count * 16) throw new Error('Prototype relaxation did not converge')
  const cluster = choose(1, true)
  occupied[cluster] = 0
  update(cluster, -1)
  const empty = choose(0, false)
  occupied[empty] = 1
  update(empty, 1)
  if (cluster === empty) break
}
const prototype = occupied.slice(), prototypeEnergy = energy.slice(), ranks = new Uint16Array(count)
// Phase I: remove clusters, assigning the low ranks backwards.
for (let rank = initialCount - 1; rank >= 0; rank--) {
  const point = choose(1, true)
  ranks[point] = rank
  occupied[point] = 0
  update(point, -1)
}
// Phase II: fill voids until half the pixels are occupied.
occupied = prototype
energy = prototypeEnergy
for (let rank = initialCount; rank < count / 2; rank++) {
  const point = choose(0, false)
  ranks[point] = rank
  occupied[point] = 1
  update(point, 1)
}
// Phase III: distribute the remaining holes by removing clusters in the inverse.
const kernelSum = kernel.reduce((sum, value) => sum + value, 0)
occupied = occupied.map(value => 1 - value)
energy = energy.map(value => kernelSum - value)
for (let rank = count / 2; rank < count; rank++) {
  const point = choose(1, true)
  ranks[point] = rank
  occupied[point] = 0
  update(point, -1)
}
const bytes = Uint8Array.from(ranks, rank => Math.floor(rank * 256 / count))
const encoded = Buffer.from(bytes).toString('base64').match(/.{1,112}/g)
const output = `// Generated by scripts/generate-nebula-blue-noise.mjs; fixed seed, sigma=${sigma}.\n` +
  `export const NEBULA_BLUE_NOISE_SIZE = ${size}\n` +
  `export const NEBULA_BLUE_NOISE_BASE64 =\n${encoded.map(line => `  '${line}'`).join(' +\n')}\n`
await writeFile(new URL('../src/core/renderables/Nebula/material/blueNoiseData.ts', import.meta.url), output)
console.log(`Generated ${size}x${size} R8 blue noise (${bytes.length} bytes, ${iterations} relaxation steps)`)
